package portkit

import (
	"slices"
	"testing"
)

func TestParseProcNetTCP(t *testing.T) {
	tcp := `  sl  local_address rem_address   st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode
   0: 0100007F:0BB8 00000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 11111 1 0000000000000000 100 0 0 10 0
   1: 00000000:1F40 00000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 22222 1 0000000000000000 100 0 0 10 0
   2: 0100007F:0BB8 0100007F:D431 01 00000000:00000000 00:00000000 00000000  1000        0 33333 1 0000000000000000 20 4 30 10 -1
`
	tcp6 := `  sl  local_address                         remote_address                        st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode
   0: 00000000000000000000000001000000:1435 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 44444 1 0000000000000000 100 0 0 10 0
   1: 00000000000000000000000000000000:0FA0 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 55555 1 0000000000000000 100 0 0 10 0
   2: 0000000000000000FFFF00000100007F:1388 00000000000000000000000000000000:0000 0A 00000000:00000000 00:00000000 00000000  1000        0 66666 1 0000000000000000 100 0 0 10 0
`
	got := append(parseProcNetTCP([]byte(tcp)), parseProcNetTCP([]byte(tcp6))...)
	want := []procSocket{
		{Socket{"127.0.0.1", 3000}, "11111"},
		{Socket{"0.0.0.0", 8000}, "22222"},
		{Socket{"::1", 5173}, "44444"},
		{Socket{"::", 4000}, "55555"},
		{Socket{"127.0.0.1", 5000}, "66666"},
	}
	if !slices.Equal(got, want) {
		t.Errorf("parseProcNetTCP = %v, want %v", got, want)
	}
}
